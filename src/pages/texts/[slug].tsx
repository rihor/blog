import type { GetStaticPaths, GetStaticProps, NextPage } from 'next'
import Link from 'next/link'
import { useMemo } from 'react'

import * as prismic from '@prismicio/client'

import SEO from '../../components/SEO'
import type { CustomDocument } from '../../lib/prismic'
import { requestTextBySlug, retrieveAllSlugs } from '../../lib/prismic'
import styles from '../../styles/Slug.module.scss'

interface Props {
  text: CustomDocument
}

const TextPage: NextPage<Props> = ({ text }) => {
  const collab = text?.data?.collab.slug

  const bodyInnerHTML = useMemo(
    () => ({
      __html: prismic.asHTML(text.data.body as prismic.RichTextField)
    }),
    [text.data.body]
  )

  return (
    <div>
      <main className={styles.main}>
        <SEO
          title={
            text.data?.title
              ? prismic.asText(text.data.title as prismic.RichTextField)
              : 'Texto'
          }
          description={text.data?.body ? text.data.body[0].text : 'Texto'}
        />
        <nav className={styles.nav}>
          <Link href="/texts">TEXTOS</Link>
          <a href="https://rihor-portfolio.now.sh">PORTFOLIO</a>
        </nav>
        {text.data && (
          <article className={styles.text}>
            <header className={styles.header}>
              <h1>
                {prismic.asText(text.data.title as prismic.RichTextField)}
              </h1>
              <h2>
                {prismic.asText(text.data.subtitle as prismic.RichTextField)}
              </h2>
              {collab && (
                <h3>
                  Escrito em colaboração com <span>{collab}</span>
                </h3>
              )}
            </header>
            {/* HTML is generated by Prismic's serializer from our own CMS content */}
            {/* eslint-disable-next-line @eslint-react/dom-no-dangerously-set-innerhtml */}
            <div dangerouslySetInnerHTML={bodyInnerHTML} />
          </article>
        )}
      </main>
    </div>
  )
}

export const getStaticPaths: GetStaticPaths = async () => {
  const allSlugs = await retrieveAllSlugs()

  const paths = allSlugs.map(slug => {
    return {
      params: { slug: slug.uid as string }
    }
  })

  console.log(paths)

  return {
    paths,
    fallback: 'blocking'
  }
}

export const getStaticProps: GetStaticProps<Props> = async ({ params }) => {
  const slug = String(params?.slug)

  const textResult = await requestTextBySlug(slug)

  return {
    props: {
      text: textResult
    },
    revalidate: 1
  }
}

export default TextPage
